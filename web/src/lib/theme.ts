export const THEMES = ["light", "dark"] as const;
export type Theme = (typeof THEMES)[number];
export const THEME_LABEL: Record<Theme, string> = { light: "Institutional (light)", dark: "Operations room (dark)" };
export const THEME_STORAGE_KEY = "urbs.theme";

export function resolveTheme(stored: string | null, prefersDark: boolean): Theme {
  if (stored && (THEMES as readonly string[]).includes(stored)) return stored as Theme;
  return prefersDark ? "dark" : "light";
}

