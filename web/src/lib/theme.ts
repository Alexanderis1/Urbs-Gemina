// "hypothetical" inputs are drawn with the what-if style, so they share its key.
export type KindKey = Exclude<DataKind, "hypothetical"> | "what_if";

/** One vocabulary for the whole app. The glyph differs per kind so the label never relies on colour alone. */
export const KIND_META: Record<KindKey, { label: string; hint: string; glyph: "solid" | "half" | "dashed" | "diamond" | "empty" }> = {
  real: { label: "Real", hint: "Open or official data, as published by its source.", glyph: "solid" },
  estimated: { label: "Estimated", hint: "Modelled or crowd-sourced estimate. Always shown with a range.", glyph: "half" },
  simulated: { label: "Simulated", hint: "Generated by a simulator (traffic loops only). Never a measurement.", glyph: "dashed" },
  what_if: { label: "What-if", hint: "A hypothetical change entered by the user, not existing data.", glyph: "diamond" },
  not_available: { label: "Not available", hint: "This layer could not be read, so it was not used.", glyph: "empty" },
};

function luminance(hex: string): number {
  const n = hex.replace("#", "");
  const ch = [0, 2, 4].map((i) => parseInt(n.slice(i, i + 2), 16) / 255).map((c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
  return 0.2126 * ch[0]! + 0.7152 * ch[1]! + 0.0722 * ch[2]!;
}

/** WCAG 2 contrast ratio between two #rrggbb colours. */
export function contrastRatio(a: string, b: string): number {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x) as [number, number];
  return (hi + 0.05) / (lo + 0.05);
}
