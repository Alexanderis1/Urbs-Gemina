import { useEffect, useState } from "react";
import { KindBadge } from "@/components/Badge";
import { RunMeta } from "@/components/RunMeta";
import { useSession } from "@/lib/runlog";
import type { DataStatusResult, Envelope } from "@/api/types";

export default function DataHonesty() {
  const { run } = useSession();
  const [env, setEnv] = useState<Envelope<DataStatusResult> | null>(null);
  const [error, setError] = useState<string | null>(null);
  useEffect(() => {
    run<DataStatusResult>("data_status", {}).then(setEnv, (e: unknown) => setError(String(e)));
  }, [run]);

  return (
    <div className="mx-auto max-w-5xl space-y-4 p-4">
      <h1 className="text-xl font-semibold">Data honesty</h1>
      <p className="text-sm text-stone-600">
        Every layer is <KindBadge kind="real" /> (open or official data), <KindBadge kind="estimated" /> (crowd-sourced or
        modelled) or <KindBadge kind="simulated" /> (only the traffic loop sensors, generated by a simulator because no open feed exists; never a measurement). Hypothetical changes in the Scenario lab and Sport screen are marked WHAT-IF.
      </p>
      {error && <p className="text-sm text-red-700">{error}</p>}
      {env && (
        <div className="card overflow-x-auto">
          <table className="w-full text-left text-sm">
            <thead className="label">
              <tr>
                <th className="py-1">Layer</th>
                <th>Kind</th>
                <th>Provider</th>
                <th>Licence</th>
                <th>Last update</th>
                <th>Validation</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-stone-100">
              {env.result.layers.map((l) => (
                <tr key={l.layer}>
                  <td className="py-1.5 font-medium">{l.layer}</td>
                  <td>
                    <KindBadge kind={l.kind} />
                  </td>
                  <td>{l.provider}</td>
                  <td>{l.licence}</td>
                  <td className="whitespace-nowrap">{l.last_update}</td>
                  <td>{l.validation ?? "—"}</td>
                </tr>
              ))}
            </tbody>
          </table>
          <div className="mt-3">
            <RunMeta env={env} />
          </div>
        </div>
      )}
    </div>
  );
}
