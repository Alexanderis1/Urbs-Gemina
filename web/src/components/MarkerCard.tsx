import { Crosshair, X } from "lucide-react";
import type { ReactNode } from "react";
import type { DataKind } from "@/api/types";
import { KindBadge } from "@/components/Badge";
import { locale, texts, tr } from "@/lib/i18n";
import type { Resource, ResourceReading } from "@/lib/resource";
import { GLYPHS, type Glyph } from "@/map/markerGlyphs";

